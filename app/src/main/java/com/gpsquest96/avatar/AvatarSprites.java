    // [genero 0=chico, 1=chica][direccion][fase 0=parado/A, 1=B]
    private static final String[][][] FRAMES = {
        { // BOY
            {BOY_FRONT_A, BOY_FRONT_B}, // FRONT
            {BOY_BACK_A, BOY_BACK_B},   // BACK
            {BOY_SIDE_A, BOY_SIDE_B},   // SIDE
        },
        { // GIRL
            {GIRL_FRONT_A, GIRL_FRONT_B}, // FRONT
            {GIRL_BACK_A, GIRL_BACK_B},   // BACK
            {GIRL_SIDE_A, GIRL_SIDE_B},   // SIDE
        },
    };

    // Decodificados en cache (solo lectura: no mutar lo devuelto).
    private static final int[][][][] CACHE = new int[2][3][2][];

    private AvatarSprites() {
    }

    /** Cuadro codificado (para tests). */
    public static String frameData(AvatarData.Gender gender, Direction dir, int phase) {
        return FRAMES[genderIndex(gender)][dirIndex(dir)][phase & 1];
    }

    /** Pixeles ARGB del cuadro pedido (FRAME_W x FRAME_H). */
    public static int[] pixels(AvatarData.Gender gender, Direction dir, int phase) {
        int g = genderIndex(gender);
        int d = dirIndex(dir);
        int p = phase & 1;
        int[] cached = CACHE[g][d][p];
        if (cached == null) {
            cached = decode(FRAMES[g][d][p]);
            CACHE[g][d][p] = cached;
        }
        return cached;
    }

    /** Pixeles del cuadro espejados en horizontal (lado izquierdo). */
    public static int[] pixelsMirrored(AvatarData.Gender gender, Direction dir, int phase) {
        return mirror(pixels(gender, dir, phase));
    }

    /** Decodifica un cuadro codificado a ARGB (FRAME_W x FRAME_H). */
    public static int[] decode(String encoded) {
        if (encoded == null || encoded.length() != FRAME_W * FRAME_H) {
            throw new IllegalArgumentException(
                    "cuadro corrupto: longitud " + (encoded == null ? -1 : encoded.length()));
        }
        int[] out = new int[FRAME_W * FRAME_H];
        for (int i = 0; i < out.length; i++) {
            int idx = ALPHABET.indexOf(encoded.charAt(i));
            if (idx < 0 || idx >= PALETTE.length) {
                throw new IllegalArgumentException("cuadro corrupto: caracter fuera de paleta");
            }
            out[i] = PALETTE[idx];
        }
        return out;
    }

    /** Espejo horizontal de un cuadro (nuevo array). */
    public static int[] mirror(int[] px) {
        if (px == null || px.length != FRAME_W * FRAME_H) {
            throw new IllegalArgumentException("cuadro corrupto: longitud invalida");
        }
        int[] out = new int[px.length];
        for (int y = 0; y < FRAME_H; y++) {
            for (int x = 0; x < FRAME_W; x++) {
                out[y * FRAME_W + x] = px[y * FRAME_W + (FRAME_W - 1 - x)];
            }
        }
        return out;
    }

    /**
     * Direccion segun rumbo (bearing 0=N, 90=E, 180=S, 270=O). Sectores de 90
     * grados centrados en los cardinales.
     */
    public static Direction directionFor(float bearingDeg) {
        float b = ((bearingDeg % 360f) + 360f) % 360f;
        if (b < 45f || b >= 315f) return Direction.BACK;
        if (b < 135f) return Direction.SIDE;
        if (b < 225f) return Direction.FRONT;
        return Direction.SIDE;
    }

    /** true = mirar al oeste (lado espejado). */
    public static boolean mirrorFor(float bearingDeg) {
        float b = ((bearingDeg % 360f) + 360f) % 360f;
        return b >= 225f && b < 315f;
    }

    /**
     * Fase de caminata: 0 = parado (sin movimiento durante IDLE_MS), 1 = paso
     * alterno. Mientras hay movimiento alterna 0/1 cada STEP_MS.
     */
    public static int phaseFor(long nowMs, long lastMoveMs) {
        if (nowMs - lastMoveMs > IDLE_MS) return 0;
        return (int) ((nowMs / STEP_MS) % 2);
    }

    private static int genderIndex(AvatarData.Gender gender) {
        return (gender == AvatarData.Gender.GIRL) ? 1 : 0;
    }

    private static int dirIndex(Direction dir) {
        switch (dir) {
            case BACK: return 1;
            case SIDE: return 2;
            case FRONT:
            default: return 0;
        }
    }
